/**
 * Validation function to verify mathematical integrity of all levels.
 * Confirms that for every level:
 * sum(steps.increment) === minuend - subtrahend === diff
 */
export function validateAllLevels() {
  MATH_O_LANTERN_LEVELS.forEach((level) => {
    const sumIncrements = level.steps.reduce((sum, s) => sum + s.increment, 0);
    const expectedDiff = level.minuend - level.subtrahend;
    if (sumIncrements !== expectedDiff || sumIncrements !== level.diff) {
      console.error(
        `Math error in level ${level.id}: sum=${sumIncrements}, expected=${expectedDiff}, diff=${level.diff}`
      );
    }
  });
}

